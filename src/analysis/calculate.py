# 조사 — 이름을 넣으면 **받침에 따라 조사가 달라진다**
#
#     급여·연금을 이 기관으로 받기   →  농협은행주식회사**으로**  (틀렸다 · `로` 다)
#     이 기관과 첫 거래            →  카카오뱅크**과**          (틀렸다 · `와` 다)
#     이 기관을 주로 쓰기           →  카카오뱅크**을**          (틀렸다 · `를` 다)
#
# 세 라벨이 다 그렇다. 조사를 피해 문장을 비틀 수도 있지만(`이 기관에서 …`) 그러면
# 말이 어색해진다 — **틀린 문법도 화면이 하는 거짓말의 일종**이므로 맞춰서 쓴다.
#
# 이 함수는 **우리가 지은 라벨 위에서만** 돈다. 이름 바로 뒤에 붙은 조사만 고치므로
# 공시 문구나 상품명에는 손대지 않는다.
JOSA_PAIRS = (("으로", "로"), ("과", "와"), ("을", "를"), ("은", "는"), ("이", "가"))


def has_jongseong(word: str, particle: str = "") -> bool:
    """마지막 글자에 받침이 있나. 한글이 아니면 없는 것으로 본다.

    `으로/로` 만 예외다 — 받침이 `ㄹ` 이면 `로` 를 쓴다(`서울로`).
    """
    if not word:
        return False
    code = ord(word[-1]) - 0xAC00
    if not 0 <= code <= 11171:            # 숫자·영문으로 끝나는 이름
        return False
    jong = code % 28
    if jong == 0:
        return False
    return not (particle == "으로" and jong == 8)      # 8 = ㄹ


def fix_josa(text: str, name: str) -> str:
    """`이 기관` 자리에 `name` 을 넣은 뒤 조사를 맞춘다."""
    for have, none in JOSA_PAIRS:
        right = have if has_jongseong(name, have) else none
        for wrong in (have, none):
            if wrong != right:
                text = text.replace(name + wrong, name + right)
    return text


