# ── 가입 채널 — 편의성 축 1번을 화면에 올린다 (이슈 #22 · `problem.md` §6)
#
# **왜** — 2026-08-31 사람 세션에서 스코프 밖 금리 경고(A7)를 보고도 안 넓힌 이유가
# *"주거래도 아니고 연고도 없고 실물을 본 적도 없다"* 였다. 그 판단에 필요한 정보가
# **비대면 가입 가능 여부**인데 화면에 없었다. `join_way` 는 765상품에 다 채워져 있다.
#
#     은행권 97      영업점에서만 0건 (0%)      · 비대면에서만 51건 (53%)
#     저축은행 668   영업점에서만 **263건 (39%)** · 비대면에서만 356건 (53%)
#
# **점수에 넣지 않는다.** `problem.md` §6 이 정한 대로 편의성은 **축으로 보여주고**
# 가중치는 사용자가 정한다. 선호 가중치(로드맵 D7)가 들어오기 전까지는 표시만 한다.
#
# **빈 값은 추측하지 않는다** — 2건이 비어 있고 `채널미상` 으로 낸다.
NONFACE = ("인터넷", "스마트폰")        # 비대면으로 치는 채널


def channel_label(join_way: str) -> str:
    """`join_way` 를 화면 한 단어로. 모르면 `채널미상` 이다 — 추측하지 않는다."""
    if not join_way:
        return "채널미상"
    nonface = any(k in join_way for k in NONFACE)
    branch = "영업점" in join_way
    if nonface and branch:
        return "비대면·영업점"
    if nonface:
        return "비대면"
    if branch:
        return "영업점만"
    return "채널미상"                   # 전화·기타 뿐인 경우 — 실측 0건이지만 열어 둔다


# ── 신원 (`prereg-13` · 이슈 #25)
#
# **상품코드는 상품의 신원이 아니다.** 기관을 넘어 유일하지 않다 — 저축은행 기관명
# 30종 아래 기관코드가 58개이고, 하나저축은행 세 법인이 전부 상품코드 `240001`
# "정기예금" 을 쓴다. 상품코드만 세면 92개, 기관코드까지 보면 **183개**다.
#
# 이 버그는 화면에서 거짓말로 나왔다 — 질문 루프가 *"이 답 하나가 상품 N개의 판정을
# 엽니다"* 라고 쓰는데 그 N 이 92 기준이었다. #24 에서 화면 계약 A11 이 2,388건
# 불통과로 뜬 것이 실마리였고(짝을 코드로 지었다), 쫓아가니 화면 쪽 버그였다.
#
# **한 곳에서만 계산한다.** 두 곳에서 다르게 세면 이 버그가 그대로 재발한다.
def product_key(s: dict) -> tuple:
    """상품 하나의 신원 — `(기관코드, 상품코드)`. 사용자에게 "정기예금" 은 하나다."""
    return (s.get("co_no") or "", s["code"])


def row_key(s: dict) -> tuple:
    """행 하나의 신원 — `(기관코드, 상품코드, 단리/복리, 적립방식)`.

    조사로 확정했다 — 은행권 79 = 79 · 저축은행 297 = 297 로 **원천 필드가 행을
    남김없이 설명한다**(완전 중복 레코드 0건이라 수집 문제도 아니다).

    **행과 상품은 다른 것을 잰다** (`prereg-13` §1). 같은 상품의 단리 행은 닫히고
    복리 행은 안 닫힐 수 있으니 **행은 추출 품질의 단위**이고, 사용자에게 "정기예금"
    은 하나이니 **상품은 화면의 단위**다. 지금까지 코드가 우연히 그렇게 돼 있었고
    아무 데도 안 적혀 있었다.
    """
    return (s.get("co_no") or "", s["code"],
            s.get("rate_type") or "", s.get("rsrv_type") or "")


def scope_rows(rows: list[dict], company: str | None = None,
               kinds: str | None = None) -> list[dict]:
    """후보 집합을 자른다. 기관은 부분 일치다 — `"우리"` 로 `우리은행` 이 걸린다."""
    out = rows
    if company:
        wants = [w.strip() for w in company.split(",") if w.strip()]
        out = [r for r in out if any(w in (r.get("company") or "") for w in wants)]
    if kinds:
        ks = [k.strip() for k in kinds.split(",") if k.strip()]
        out = [r for r in out if r["kind"] in ks]
    return out


def question_plan(rows: list[dict], by_pair: dict) -> dict[str, set[str]]:
    """`{유형 상태 키: {문구 단위 후속 질문 키}}`. "모두 예" 를 가정한 최대 집합이다.

    **키가 기관별로 갈린다** (F6 · `prereg-15`) — 기관 상대 유형은 `자동이체@국민은행`
    처럼 기관이 붙는다. 그래서 은행권 12개월 유형 질문이 15개에서 **(유형, 기관) 쌍
    56개 + 기관 무관 9개**로 늘어나는데, 목록 질문 하나가 안 고른 기관을 전부 유도하므로
    **거래 은행 1곳 사용자는 16개**로 끝난다(`prereg-15` P5).

    분모(*"전부 답하면 질문 N개"*)는 **거래 은행이 전부일 때**의 값이다. 그래서
    목록에 답하면 분모가 줄어들고, `questions_left()` 는 절대 늘어나지 않는다(A4).
    """
    plan: dict[str, set[str]] = {}
    for row in rows:
        got = by_pair.get(row["pair_id"])
        if not got or not got.get("schema_ok"):
            continue
        company = row.get("company") or ""
        for it in (got["parsed"].get("items") or []):
            if not it.get("applies_to_term"):
                continue
            verdict = no_condition(it)
            if verdict == "제외":
                continue
            kind = UNCLEAR_TYPE if verdict == "조건불명" else it.get("condition_type")
            if kind in UNDECIDABLE or kind in ALWAYS_MET:
                continue                      # 물어도 소용없다 — 추첨·항상 충족
            it = {**it, "_기관": company}      # 문구 키가 기관을 담는다 (§1.2)
            key = type_key(kind, company)
            plan.setdefault(key, set())
            q = threshold_question(it) if has_threshold(it) else None
            if q:
                plan[key].add(q)              # 문구 단위 후속 질문 (`prereg-10`)
    # 목록 질문 — 기관 상대 유형이 하나라도 있으면 **맨 먼저** 묻는다
    if any("@" in k for k in plan):
        plan[TRADED_KEY] = set()
    return plan


def questions_answered(plan: dict[str, set[str]], state: dict) -> int:
    """**실제로 답한 질문 수.** 화면의 "답한 질문 N" 은 이 값이어야 한다.

    옛 화면은 `전체 - 남은` 을 "답한 질문" 이라고 표시했는데, **거짓이었다** —
    `"아니오"`·`"모르겠다"` 는 딸린 문구 질문까지 같이 지우므로 그 차이가 답한 수보다
    커진다. 실측 세션에서 11개를 답한 사람에게 **"답한 질문 22개"** 라고 표시했다.
    사람이 지적한 것이다 — *"13 다음 14지. 전체 질문수를 39에서 30으로 줄이라는 뜻이었다."*

    그래서 화면은 이렇게 쓴다.
        답한 질문   이 함수 (한 번에 하나씩만 늘어난다)
        전체        답한 + 남은 (지워진 만큼 줄어든다)
        남은        `questions_left()`
    """
    # **유도된 답은 세지 않는다** — 사용자가 답한 것만 센다. 유도는 상태에 안 쓰고
    # `answer_of()` 가 읽을 때 계산하므로, 여기서는 `state` 에 있는 것만 보면 된다
    types = sum(1 for kind in plan if kind in state)
    clauses = sum(1 for subs in plan.values() for c in subs if c in state)
    return types + clauses


def questions_left(plan: dict[str, set[str]], state: dict) -> int:
    """화면에 띄울 남은 질문 수. 이 값은 답할 때마다 절대 늘어나지 않는다."""
    n = 0
    for key, subs in plan.items():
        if key == TRADED_KEY:                 # 목록 질문 하나 (F6)
            n += 0 if key in state else 1
            continue
        kind, _at, company = key.partition("@")
        answered = answer_of(kind, company, state)     # 유도된 답도 답이다
        if answered is None:
            n += 1 + len(subs)                # 아직 안 물었다 — 후속까지 상정한다
        elif answered is False or answered == UNSURE:
            n += 0                            # 아니다/모른다 — 후속도 물을 필요가 없다
        else:
            n += sum(1 for s in subs if s not in state)
    return n


def rank_questions(scored: list[dict],
                   state: dict | None = None) -> list[tuple[str, dict]]:
    """되물을 질문을 **고정된 우선순위**로 줄 세운다. 위 주석이 그 규칙이다.

    **1순위가 세는 것은 `product_key()` 로 센 상품 수다** (`prereg-13` · 이슈 #25).
    전에는 `code` 로 셌고, 그래서 서로 다른 저축은행 법인의 같은 상품코드가 하나로
    합쳐졌다 — 저축은행 상품이 92개로 보였다(참값 183). 규칙을 바꾼 것이 아니라
    **규칙이 이미 "상품 커버리지" 라고 말하던 것을 그대로 계산되게 고친 것**이다.

    이 함수는 화면 문구(*"이 답 하나가 상품 N개를 엽니다"*)와 질문 순서를 **동시에**
    만든다. 그래서 화면을 고치면 순서가 바뀌고 예산 12개 확정률이 움직인다 —
    재등록 사유·편향 방향·완화 조치는 `prereg-13` §2 에 **고치기 전에** 적었다.
    """
    asks: dict[str, dict] = {}
    for s in scored:
        for q in s.get("questions", []):
            slot = asks.setdefault(q["key"], {"unit": q["unit"], "products": set(),
                                              "needs": set(), "kind": q["kind"],
                                              "evidence": set(), "출처": {}})
            slot["products"].add(product_key(s))
            if q["need"] is not None:
                slot["needs"].add(q["need"])
            if q["evidence"]:
                slot["evidence"].add(q["evidence"])   # 자르지 않는다 (`prereg-10` §6)
                # **문구가 어느 기관 것인지 같이 담는다** (2026-09-02 · 사람 완주 1런).
                #
                # 유형 질문은 문구를 **여러 기관에서 모아 온다** — 실측으로 유형 16개
                # 중 15개가 그렇고, `첫거래_신규고객` 은 기관 10곳에서 온다. 그런데
                # 문구의 8.6%가 "당행/본행/자행" 을 쓴다. 기관을 안 붙이면
                # **가리키는 대상이 사라져서 사용자가 답을 고를 수 없다.**
                #
                # 관측된 그대로 — "당행 원화 정기예금 보유이력이 없는 경우 0.50%" 를
                # 보고 *"당행이 어디인지 모르겠다"*, "③탑스, 주거래 고객" 을 보고
                # *"탑스가 무슨 말인지 모르겠다"* 였다. `0027` 이 문구를 **자르지**
                # 않게 했지만 **떼어내는** 것은 막지 못했다.
                #
                # 데이터에는 있었다 — 문구는 상품 행에서 왔고 그 행에 기관이 있다.
                # `slot["evidence"]` 는 그대로 둔다(문구 단위 상태 키가 문구
                # 문자열에서 나오므로 건드리면 답·세션·측정이 흔들린다).
                slot["출처"].setdefault(q["evidence"], set()).add(
                    s.get("company") or "")
    ordered = sorted(asks.items(), key=lambda kv: (-len(kv[1]["products"]), kv[0]))

    # **목록 질문이 맨 앞이다** (F6 · `prereg-15` §1). 순서 규칙을 깨는 것이 아니라
    # **이 질문만 다른 질문을 유도**하기 때문이다 — 답 하나가 안 고른 기관의 조건을
    # 전부 정하므로, 뒤에 물으면 이미 물어본 것을 다시 정하는 꼴이 된다.
    # `0018` 의 커버리지 순은 그 아래에서 그대로 돈다.
    rel = [k for k, _ in ordered if "@" in k and "#" not in k]
    if rel and (state is None or TRADED_KEY not in state):
        # **표기 이름 순으로 세운다** (F5) — 사용자가 눈으로 찾는 순서여야 한다.
        # `주식회사 카카오뱅크` 를 공시 이름으로 세우면 ㅈ 자리에 있는데 화면에는
        # `카카오뱅크` 로 보여서 ㅋ 자리에서 찾게 된다
        banks = sorted({s.get("company") or "" for s in scored if s.get("company")},
                       key=org_label)
        opened = {product_key(s) for s in scored
                  if any("@" in q["key"] and "#" not in q["key"]
                         for q in s.get("questions", []))}
        ordered.insert(0, (TRADED_KEY, {
            "unit": LIST_UNIT, "kind": LIST_KIND, "products": opened,
            "needs": set(), "evidence": set(), "출처": {}, "기관": banks}))
    return ordered


