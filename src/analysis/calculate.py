# `iM함께예금`은 `g1` 에 `[0.1 x 5]` 가 들어 있는데 공시 폭이 0.45라 **다섯 개가 다
# 더해져야** 맞는다 — 중복 적용 불가가 아니라 별개 조건 다섯을 한 그룹으로 묶은 것이다.
