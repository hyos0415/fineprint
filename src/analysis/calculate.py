# 단위 목록은 아래 MONEY_UNIT 과 같아야 한다 — 여기서 놓치면 임계인 줄 모르고
# 사용자 답을 그대로 충족으로 세어 과대 진술이 된다.
# **띄어쓰기가 없어도 잡아야 한다.** `(?![가-힣])` 만 두면 `"1천만원이상"` 이
