#
#     은행권 22개 = 유형 15 + 수치 후속 7      저축은행 27개 = 유형 13 + 수치 후속 14
#
# 이 집합은 **아무것도 안 물은 상태에서 추출 데이터만으로 미리 계산된다.** 시뮬레이션이
# 필요 없다. 실측으로 전부 답했을 때의 실제 질문 수(22 · 27)와 정확히 일치한다.


