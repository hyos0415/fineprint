# 한 유형 아래 **대상이 서로 다른 문구**가 묶여 있기 때문이다.
#
#     타상품_보유동시가입 — 금액이 얼마입니까?
#         "②적립식예금 잔액 10만원 이상 보유"
#         "수익증권(펀드)을 3천만원 이상 보유 시"
#         "정기예금 500만원이상(만기 1년이상) 가입하고 만기일 전일까지 유지"
#
# 적립식예금 잔액·펀드 보유액·정기예금 가입액은 **같은 축이 아니다.** 숫자 하나로
# 답할 수 없고, 입력 폼으로 바꿔도 필드 하나로는 못 받는다.
#
# **그래서 판정 단위를 (유형)에서 (유형 + 문구)로 내린다.** 공시 문구가 질문 옆의
# 참고 자료가 아니라 **질문 문장 자체**가 된다 — `0024` P1 이 강해지는 방향이고,
# 사용자는 자기 상황을 그 문구에 대조하기만 하면 된다(숫자 계산이 사라진다).
#
# **키는 문구 해시다.** `0018` 이 정렬 2순위를 *"내용에 무관한 기준을 일부러 골랐다"* 로
# 못 박았으므로 문구 텍스트를 그대로 키로 쓰지 않는다. 같은 문구는 항상 같은 키가
# 된다(`0020` 자기 일관성과 같은 성질).
CLAUSE_HASH_BYTES = 4        # 8자 16진수. 실측 문구 종수는 권역당 100 미만이다


def is_state_key(key: str) -> bool:
    """이것이 **유효한 사용자 상태 키**인가 — 한 곳에서 판정한다.

    모양이 셋이다.
    ```
    카드실적                 조건 유형 (`CONDITION_TYPES`)
    카드실적_금액 · _횟수      수치 후속 (B안 · 임계 비교)
    카드실적#a3f1c2d9        **문구 단위**  ← `clause_key()` 가 만든다 (`0027`·`prereg-10`)
    ```

    **왜 함수로 뺐나** (2026-09-02 · 사람 완주 2런). 이 판정이 두 군데 있었다 —
    CLI 의 `--state` 파싱과 웹 서버의 요청 검증. CLI 는 문구 단위 키를 `--state` 로
    받지 않으므로(대화 루프가 상태에 직접 넣는다) 셋째 모양을 몰라도 됐는데,
    **웹은 그 키를 요청으로 받는다.** 그래서 복사된 검증이 유효한 답을 거부했다 —
    사람이 질문에 답하다가 `모르는 조건 유형: ['목표달성_납입실적#4676c2ed']` 로 막혔다.

    `0039` 가 정한 것과 같은 자리다 — **한쪽만 쓰는 규칙을 만들지 않는다.**
    """
    if key == TRADED_KEY:                     # 거래해 본 기관 목록 (F6)
        return True
    base, sep, _hash = key.partition("#")
    kind, at, _co = base.partition("@")
    if sep:                                   # 문구 단위 — 앞부분이 조건 유형이어야 한다
        return kind in CONDITION_TYPES
    if at:                                    # 기관이 붙은 유형 키 (F6)
        return kind in INSTITUTION_RELATIVE
    if key in CONDITION_TYPES:
        return True
    head, _, tail = key.rpartition("_")       # 수치 후속
    return tail in ("금액", "횟수") and head in CONDITION_TYPES


def clause_key(item: dict) -> str:
    """`카드실적@국민은행#a3f1c2d9` — 조건 유형 + **기관** + 근거 문구 해시.

    **기관을 넣은 이유는 같은 문구를 두 기관이 쓰기 때문이다** (`prereg-15` §1.2).
    실측으로 은행권 문구 단위 키 209개 중 1개(0.5%)가 그랬다
    (`급여_연금이체#deb3d786` — 국민은행·케이뱅크). 저축은행은 133개 중 0개다.
    **작지만 기관별로 갈리는 것을 안 가른 것과 같은 결함**이라 키에서 없앤다.

    기관 상대 유형이 아니어도 붙인다 — 문구는 상품 행에서 왔고 그 행에 기관이 하나뿐이다.
    """
    ev = re.sub(r"\s+", " ", (item.get("evidence") or "")).strip()
    h = hashlib.blake2s(ev.encode("utf-8"), digest_size=CLAUSE_HASH_BYTES).hexdigest()
    return f"{type_key(item.get('condition_type') or '', item.get('_기관') or '', force=True)}#{h}"


def type_key(kind: str, company: str, force: bool = False) -> str:
    """조건 유형의 **상태 키**. 기관 상대 유형이면 기관을 붙인다.

    `force` 는 문구 단위 키 전용이다 — 문구는 유형과 무관하게 기관 하나에 붙는다.
    """
    if company and (force or kind in INSTITUTION_RELATIVE):
        return f"{kind}@{company}"
    return kind


def traded_banks(state: dict):
    """사용자가 *"거래해 본"* 이라고 고른 기관들. 아직 안 물었으면 None.

    모양이 틀린 값(불리언 등)은 **안 물어본 것으로 본다.** 문자열을 그대로 쓰면
    `"국민은행" in "국민은행저축은행"` 이 참이라 조용히 엉뚱한 판정이 된다.
    """
    banks = state.get(TRADED_KEY)
    if banks is None or banks == UNSURE or isinstance(banks, list):
        return banks
    return None


def unknown_banks(state: dict, rows: list[dict]) -> list[str]:
    """목록 답에 **후보에 없는 기관**이 있나. 있으면 그 이름들을 낸다 (F6).

    **한 곳에서만 판정한다** — CLI 의 `--banks` 와 웹 요청이 각자 검증하면 한쪽만
    고치게 된다(`0039` 가 정한 것과 같은 자리). 조용히 무시하면 **사용자가 고른 것과
    계산에 들어간 것이 달라진다** — 안 고른 것으로 처리되어 그 기관의 실적 조건이
    "아니오" 로 유도된다.
    """
    banks = traded_banks(state)
    if not isinstance(banks, list):
        return []
    known = {r.get("company") or "" for r in rows}
    return [b for b in banks if b not in known]


def answer_of(kind: str, company: str, state: dict):
    """이 기관에서 이 조건 유형의 답. **유도된 답까지 포함한다** (F6 · `prereg-15` §1).

    유도는 둘뿐이고 **둘 다 사용자가 이미 준 답에서 논리적으로 따라 나온다.**
    추측이 아니다(`0016`) — 우리가 모르는 것을 채우는 게 아니라, 사용자가 말한 것의
    필연적 귀결을 두 번 묻지 않는 것이다.

    ```
    ① 목록에 없는 기관     첫거래 = 예 · 나머지 실적 조건 전부 아니오
                        **거래가 없으면 그 은행에 실적이 있을 수 없다**
    ② 한 기관 안에서       첫거래 = 예  →  주거래 = 아니오
                        주거래 = 예  →  첫거래 = 아니오
                        신규이면서 동시에 주거래일 수 없다 (이슈 #44)
    ```

    **목록에 있는 기관의 첫거래는 되묻는다.** 공시 문구가 *"당행 예금 최초 가입"*
    처럼 상품군까지 좁히는 경우가 있어서, 그 은행과 거래가 있어도 참일 수 있다.
    *"거래해 본"* 의 뜻은 사용자가 정한다(`prereg-15` §4) — 우리가 좁히지 않는다.
    """
    if kind not in INSTITUTION_RELATIVE or not company:
        return state.get(kind)
    key = f"{kind}@{company}"
    if key in state:
        return state[key]
    other = MAIN_DEAL if kind == FIRST_DEAL else FIRST_DEAL if kind == MAIN_DEAL else ""
    if other and state.get(f"{other}@{company}") is True:
        return False                          # 유도 ② — 배타
    banks = traded_banks(state)
    if banks is None or banks == UNSURE:
        return None                           # 목록을 아직 안 물었다 / 모른다고 답했다
    if company in banks:
        return None                           # 거래해 본 기관 — 실적을 되묻는다
    return True if kind == FIRST_DEAL else False      # 유도 ①


def threshold_question(item: dict) -> str | None:
    """임계가 붙은 조건을 판정하려면 무엇을 물어야 하는가 — **문구 단위 상태 키**.

    계단식(단계가 둘 이상)이면 `None` 이다. 예/아니오로도 판정할 수 없다 —
    "10회면 0.3%p, 15회면 0.5%p" 인데 우리는 0.5%p 만 알기 때문이다(`0023`).
    """
    if parse_threshold(item) is None:
        return None
    return clause_key(item)


def question_for(item: dict, state: dict) -> dict | None:
    """판정 못 한 항목을 **되물을 질문**으로 바꾼다. 물어도 소용없으면 None.

    **문구를 그대로 인용한다.** 우리가 요약하면 사용자가 판단할 근거를 빼앗는다 —
    "ESG 실천 우대금리 1.00%" 처럼 공시가 무엇을 하라는지 안 밝힌 조건도, 원문을
    보여주고 "충족하십니까 / 모르겠습니다" 를 받는 것이 우리가 대신 추측하는 것보다 낫다.
    """
    kind = item.get("condition_type")
    if kind in UNDECIDABLE:
        return None                      # 추첨·랜덤 — 사용자도 은행도 미리 모른다
    # **답은 기관별로 있다** (F6). 유도된 답도 답이므로 유도되면 질문이 안 나간다
    company = item.get("_기관") or ""
    answered = answer_of(kind, company, state)
    if answered == UNSURE:
        return None                      # 이미 물었고 "모르겠다" 였다
    if answered is False:
        return None                      # 아니오 — 유도든 직접 답이든 물을 것이 없다
    if answered and has_threshold(item):
        key = threshold_question(item)
        if key is None:
            return None                  # 계단식 — 예/아니오로도 금리를 모른다
        if state.get(key) is not None:
            return None                  # 이미 그 문구를 물었다 (모름 포함)
        # **문구가 질문 문장이 된다** (`prereg-10`). 임계 수치를 받지 않는다
        return {"key": key, "kind": kind, "unit": "예아니오", "need": None,
                "direction": None, "evidence": item.get("evidence") or ""}
    if answered is None:
        return {"key": type_key(kind, company), "kind": kind, "unit": "예아니오",
                "need": None, "direction": None,
                "evidence": item.get("evidence") or ""}
    return None


def caveats_for(items_unknown: list[dict], items_met: list[dict], state: dict) -> list[str]:
    """왜 확정하지 못했는지 · 무엇을 주의해야 하는지 사유 코드로 모은다."""
    out = []
    for it in items_unknown:
        kind = it.get("condition_type")
        answered = answer_of(kind, it.get("_기관") or "", state)     # F6
        if kind == UNCLEAR_TYPE:
            out.append("조건불명")       # 공시가 조건을 안 적었다 — 우리 잘못이 아니다
        elif kind in UNDECIDABLE:
            out.append("추첨")           # 랜덤·추첨 — 은행도 미리 모른다
        elif answered == UNSURE:
            out.append("모름")
        elif answered and has_threshold(it):
            key = threshold_question(it)
            if key is None:
                out.append("단계불명")
            elif state.get(key) == UNSURE:
                out.append("모름")       # 문구를 물었고 "모르겠다" 였다 — 되물어도 안 없어진다
            else:
                out.append("미응답")     # 문구 질문에 아직 답하지 않았다 (`prereg-10`)
        else:
            out.append("미응답")
    if any(it.get("condition_type") in ONGOING for it in items_met):
        out.append("이행필요")
    seen, uniq = set(), []
    for c in out:                        # 순서를 지키면서 중복만 뺀다
        if c not in seen:
            seen.add(c)
            uniq.append(c)
    return uniq

# ── 자기일관성 — 같은 문구는 같은 유형으로 통일한다 (`decisions/0020`)
#
# **무엇을 고치나** — 추출기가 **같은 근거 문구를 행마다 다른 유형으로** 분류한다.
# 고유 문구 372종 중 **9종 · 항목 47개(4.5%)**가 그렇다.
#
#     12개   "신규고객 또는 정기예금 중도해지고객 우대이율 0.75%p"  {첫거래 6, 주거래 6}
#      4개   "아파트관리비 이체"                       {급여_연금이체 2, 기타 1, 자동이체 1}
#      4개   "출산예정인자-배우자 포함"                  {고객군_자격 3, 기타 1}
#      3개   "온라인.재예치우대"                       {주거래 2, 비대면_채널가입 1}
#
# 같은 문구인데 상품마다 다른 질문으로 가면, **어떤 상품은 되묻고 어떤 상품은 안 묻는다.**
# 사용자가 보는 화면이 이유 없이 갈린다.
#
# **이건 별칭 사전이 아니다.** `CLAUDE.md` 5번이 금지한 것은 손으로 쓴 매핑표
# (`"아파트관리비 이체"` -> `자동이체`)다. 여기서 쓰는 것은 **데이터에 이미 있는 표**이고,
# 사람이 정하는 값이 하나도 없다. 다수결이 바뀌면 표도 따라 바뀐다.
#
# **한계를 분명히 적는다 — 이 규칙은 분산을 줄이지 편향을 줄이지 않는다.**
# `"아파트관리비 이체"`는 다수결이 `급여_연금이체`(2표)로 가는데 **틀린 답**이다
# (아파트관리비는 자동이체다). 4:1로 흔들리던 것이 **4:0으로 일관되게 틀리는** 것으로
# 바뀐다. 화면은 일관돼지고 정답률은 그대로다. 정답률을 올리려면 추출을 고쳐야 한다
# (`prereg-07` · A군 재추출).
#
# **동점이면 손대지 않는다.** 6:6인 문구가 하나 있는데(`"신규고객 또는 정기예금
# 중도해지고객..."`), 다수결로 정할 근거가 없으면 정하지 않는다. 그게 이 프로젝트가
# 반복해 온 규칙이다 — 모르는 것을 추측하지 않는다.


def unify_types(llm: dict) -> tuple[dict, dict]:
    """같은 근거 문구에 붙은 유형을 다수결로 통일한다. (바뀐 payload, 통계)"""
    votes: dict[str, Counter] = {}
    for p in llm.get("pairs", []):
        for it in (p.get("parsed") or {}).get("items", []) or []:
            ev = (it.get("evidence") or "").strip()
            if ev:
                votes.setdefault(ev, Counter())[it.get("condition_type")] += 1
    winner, tied = {}, 0
    for ev, c in votes.items():
        if len(c) < 2:
            continue
        top = c.most_common()
        if len(top) > 1 and top[0][1] == top[1][1]:
            tied += 1                     # 동점 — 근거가 없으면 정하지 않는다
            continue
        winner[ev] = top[0][0]
    n_changed = 0
    for p in llm.get("pairs", []):
        parsed = p.get("parsed") or {}
        items = parsed.get("items")
        if not items:
            continue
        new = []
        for it in items:
            ev = (it.get("evidence") or "").strip()
            want = winner.get(ev)
            if want and want != it.get("condition_type"):
                it = {**it, "condition_type": want}
                n_changed += 1
            new.append(it)
        parsed["items"] = new
    return llm, {"문구": len(winner), "동점": tied, "바뀐 항목": n_changed}


# ── 조건이 아닌 문구를 걸러낸다 (`decisions/0019` · `prereg-06` §1.8)
#
# **무엇을 잡나** — 공시가 **금리 숫자만 적고 무슨 조건인지 안 밝힌 문구**다.
# 사람이 표본 40건을 읽다가 나왔다.
#
#     "우대이율 6개월 이상 2.20%"        부산은행. 이게 조건문의 전부다
#     "계약기간 24개월 이상"             가입기간이다. applies_to_term 이 처리할 자리
#     "12개월 정기예금(대면) 기본금리(연 3.70%)+ 기본 우대금리(연 0.10%)"
#
# **왜 그냥 두면 안 되나** — 셋 다 사용자 화면에서 나쁜 방향으로 샌다.
#   `기타` 로 갔으면          "해당되십니까" 를 묻고, "예" 면 2.20%p 를 다 준 것으로 센다
#   `무조건_특판_이벤트` 로 갔으면  **아무것도 안 물어도 항상 충족**이다. 4건이 여기 있었다
# 공시가 무슨 조건인지 한 글자도 안 적었는데 우리가 "받는다" 고 계산해 보여주는 것이다.
# 이 프로젝트가 막으려던 피해 사례가 정확히 그 모양이다.
#
# **규칙 — 문구를 하드코딩하지 않는다.** 숫자와 껍데기 말을 걷어내고 **아무것도 안
# 남으면** 그건 조건이 아니다. `기타` 40건 중 정확히 13건을 집어낸다(넘치지도 모자라지도
# 않는다). 재추출이 필요 없어 비용은 $0 이다.
#
#     "우대이율 6개월 이상 2.20%"  ->  ""              조건 아님
#     "계약기간 24개월 이상"        ->  ""              조건 아님
#     "소중한 날"                 ->  "소중한날"        조건이다. 묻는다
#     "아파트관리비 이체"           ->  "아파트관리비이체"  조건이다
#
# **금액·횟수 임계가 붙은 것은 제외한다.** "1천만원 이상" 은 숫자를 걷어내면 빈 문자열이
# 되지만 **진짜 조건**이다. `has_threshold()` 로 먼저 걸러야 오탐이 안 난다.
#
# 남은 것을 둘로 가른다 — **금리 표기가 있느냐**로 가른다.
#   금리가 없다  "계약기간 24개월 이상"     항목 자체가 아니다.  **뺀다**
#   금리가 있다  "우대이율 6개월 이상 2.20%" 금액은 공시가 알려줬다. **금리는 남기고
#                                        판정 불가로 둔다** — 빼면 정보가 사라진다
NO_COND_NUM = re.compile(
    r"\d[\d,\.]*\s*(?:%p|%|개월|년|일|회|건|명|개|원|만원|천만원|억원|점|p)?")
NO_COND_SHELL = re.compile(
    r"(우대이율|우대금리|기본금리|기본|정기예금|정기적금|계약기간|가입기간|"
    r"최대|최고|최저|이상|미만|이하|초과|연|제|대면|비대면|적용|해당|"
    r"금리|이율|주기|변동|회전|시|의|및|또는|등|\(|\)|:|·|~|\+|-|,|\s)")
HAS_RATE = re.compile(r"\d[\d,\.]*\s*%")


def no_condition(item: dict) -> str | None:
    """조건이 아닌 문구인가. `"제외"` · `"조건불명"` · None 중 하나를 낸다."""
    if has_threshold(item):
        return None                        # "1천만원 이상" — 숫자를 걷어내도 진짜 조건이다
    ev = item.get("evidence") or ""
    if NO_COND_SHELL.sub("", NO_COND_NUM.sub("", ev)).strip():
        return None                        # 무언가 남았다 — 사용자에게 물을 말이 있다
    return "조건불명" if HAS_RATE.search(ev) else "제외"


# ── 질문 예산과 우선순위 (`../../docs/spec/prereg-06-matching-and-judgment.md` §2.3(1))
#
# **왜 예산이 필요한가** — 되묻기를 넣으니 은행권 범위가 0이 됐다. 그런데 실측해 보니
# **메인 층 수는 질문에 전혀 안 변하고**(은행권 64 고정), **범위 폭 평균은 질문 수의
# 단조 감소 함수**였다. 즉 "질문을 많이 만들면 지표가 좋아진다" 는 구멍이 열려 있었다.
# 선행 저장소에서 `"UNSUPPORTED"` 만 반환하는 상수 스텁이 1·2·3순위 지표를 전부 이긴
# 것과 같은 구조다. **답할 리 없는 질문 25개를 만들어도 확정률은 오른다.**
#
# 그래서 **질문 개수를 재기 전에 못 박고, 예산 안에서만 지표를 잰다**(`decisions/0018`).
# 예산을 넘는 질문은 화면에 띄우든 말든 자유지만 **평가 지표에는 안 들어간다.**
ASK_BUDGET = 12          # 평가에 반영하는 질문 개수. 수확 체감이 여기서 꺾인다

# **우선순위 규칙도 같이 못 박는다.** 안 그러면 "상위 12개" 를 사후에 고르는 우회가
# 생긴다 — 결과를 보고 유리한 질문 12개를 상위로 올리면 예산 제약이 무력해진다.
#
#   1순위   상품 커버리지 내림차순 — 그 질문 하나가 판정을 여는 상품 수
#   2순위   질문 키 사전순 — **내용에 무관한 기준을 일부러 골랐다.** 금리 크기 같은
#           의미 있는 기준을 2순위로 두면 시스템이 추출값을 키워 순위를 밀어올릴 수 있다
#
# 동점은 실제로 예산 경계에 걸린다 — 은행권 11·12위가 둘 다 7상품(`고객군_자격`·`기타`),
# 저축은행 11·12위가 둘 다 4상품이다. **누가 예산 안에 드는지를 2순위가 정한다.**
#
# 질문 하나의 단위는 **조건 유형 하나**다(`decisions/0016`). 유형 여러 개를 한 질문으로
# 합쳐 예산을 아끼는 우회를 막는다. 수치 후속 질문(`_금액`·`_횟수`)은 별도로 센다.


